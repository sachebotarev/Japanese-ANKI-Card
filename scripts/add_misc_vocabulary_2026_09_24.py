def examples(raw: str) -> tuple[str, str]:
    chunks = raw.split("§")
    if len(chunks) != 3 or any(len(MARK.findall(x)) != 1 for x in chunks):
        raise ValueError(raw)
    return (
        "<br>".join(MARK.sub(lambda m: f"<span class='study-word'>{m.group(1)}</span>", x) for x in chunks),
        "<br>".join(MARK.sub("_____", x) for x in chunks),
    )


def furigana(word: str) -> str:
    return "Y" if any(ch not in BASIC_KANJI for ch in re.findall(r"[一-龯]", word)) else "N"


def main() -> None:
    by_topic: dict[str, set[str]] = {}
    created: list[str] = []
    for line in DATA.splitlines():
        word, topic, reading, translation, jp, ru, hint, note, kanji, level, kinds = line.split("|")
        by_topic.setdefault(topic, set()).add(word)
        path = ROOT / "Карточки" / topic / f"{word}.json"
        if path.exists():
            continue
        example, blank = examples(jp)
        translations = ru.split("§")
        if len(translations) != 3:
            raise ValueError(word)
        card = {
            "Слово": word,
            "Чтение": reading,
            "Перевод": translation,
            "Подсказка": hint,
            "Пример": example,
            "Пример без слова": blank,
            "Пример перевод": "<br>".join(translations),
            "Картинка": f"masterpiece, best quality, anime illustration, square 1:1, exactly one person, {translations[2]}, visual focus: {translation}, physical object or clear action, natural pose, warm light, no text, no letters, no watermark. Negative: extra people, text, letters, logo, bad anatomy.",
            "Произношение": "",
            "Заметки": note,
            "Кандзи-разбор": kanji,
            "Показать фуригану": furigana(word),
            "Теги": [topic, *kinds.split(","), level],
        }
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(card, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        created.append(str(path.relative_to(ROOT)))
    for topic, words in by_topic.items():
        path = ROOT / "Слова" / topic
        old = path.read_text(encoding="utf-8").splitlines() if path.exists() else []
        path.write_text("\n".join(sorted({x.strip() for x in old if x.strip()} | words)) + "\n", encoding="utf-8")
    print(f"Создано: {len(created)}")
    for path in created:
        print(path)


if __name__ == "__main__":
    main()
