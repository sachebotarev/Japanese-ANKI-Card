def w(word: str) -> str:
    return f"<span class='study-word'>{word}</span>"


def card(
    theme: str,
    word: str,
    yomi: str,
    trans: str,
    hint: str,
    e1: str,
    e2: str,
    e3: str,
    t1: str,
    t2: str,
    t3: str,
    notes: str,
    kanji: str,
    show_f: str,
    tags: list[str],
    pic_hint: str,
) -> dict:
    ex = f"{e1}<br>{e2}<br>{e3}"
    span = f"<span class='study-word'>{word}</span>"
    blank = ex.replace(span, "_____")
    return {
        "Слово": word,
        "Перевод": trans,
        "Чтение": yomi,
        "Подсказка": hint,
        "Пример": ex,
        "Пример без слова": blank,
        "Пример перевод": f"{t1}<br>{t2}<br>{t3}",
        "Картинка": pic_hint,
        "Произношение": "",
        "Заметки": notes,
        "Кандзи-разбор": kanji,
        "Показать фуригану": show_f,
        "Теги": [theme, *tags],
    }


def write_card(theme: str, payload: dict) -> None:
    d = CARDS / theme
    d.mkdir(parents=True, exist_ok=True)
    (d / f"{payload['Слово']}.json").write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def append_sorted_wordlist(rel: str, new_lines: list[str]) -> None:
    path = WORDS / rel
    lines = [ln.strip() for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip()]
    for wn in new_lines:
        if wn not in lines:
            lines.append(wn)
    lines.sort()
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


