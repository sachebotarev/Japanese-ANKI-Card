def span(surface: str, sentence: str) -> str:
    if surface not in sentence:
        raise ValueError(f"«{surface}» нет в: {sentence}")
    return sentence.replace(surface, f"<span class='study-word'>{surface}</span>", 1)


def surface_forms(word: str) -> list[str]:
    """Словарная форма и типичные спряжения/варианты для подсветки в примерах."""
    forms = {word}
    if word.endswith("する"):
        stem = word[:-2]
        forms.update(
            {
                stem,
                stem + "し",
                stem + "して",
                stem + "した",
                stem + "します",
                stem + "しました",
                stem + "したい",
                stem + "しよう",
                stem + "しない",
                stem + "でき",
                stem + "できる",
                stem + "できた",
            }
        )
    if word.endswith("い") and len(word) > 1:
        stem = word[:-1]
        forms.update({stem + "く", stem + "くて", stem + "かった", stem + "くない"})
    if "を" in word:
        forms.add(word.replace("を", "を"))
        # 電話を切る → 電話を切り / 電話を切って / 電話を切りました
        right = word.split("を", 1)[1]
        left = word.split("を", 1)[0] + "を"
        for f in surface_forms(right):
            forms.add(left + f)
    if word.endswith("る"):
        stem = word[:-1]
        forms.update(
            {
                stem + "って",
                stem + "った",
                stem + "ります",
                stem + "りました",
                stem + "らない",
                stem + "れる",
                stem + "れない",
                stem + "れば",
                stem + "よう",
                stem + "て",
                stem + "た",
                stem + "ます",
                stem + "ました",
                stem + "たい",
                stem + "ない",
                stem + "ません",
                stem + "そう",
                stem + "ず",
            }
        )
    if word.endswith("く"):
        stem = word[:-1]
        forms.update({stem + "いて", stem + "いた", stem + "きます", stem + "かない"})
    if word.endswith("す"):
        stem = word[:-1]
        forms.update({stem + "して", stem + "した", stem + "します", stem + "さない"})
    if word.endswith("う") and not word.endswith(("らう",)):  # godan う / also covers 会う-type
        stem = word[:-1]
        forms.update(
            {
                stem + "って",
                stem + "った",
                stem + "います",
                stem + "いました",
                stem + "わない",
                stem + "い",
                stem + "えば",
                stem + "おう",
            }
        )
    if word.endswith("む"):
        stem = word[:-1]
        forms.update(
            {
                stem + "んで",
                stem + "んだ",
                stem + "みます",
                stem + "みました",
                stem + "まない",
                stem + "めば",
                stem + "もう",
            }
        )
    if word.endswith("ぶ"):
        stem = word[:-1]
        forms.update(
            {
                stem + "んで",
                stem + "んだ",
                stem + "びます",
                stem + "びました",
                stem + "ばない",
                stem + "べば",
                stem + "ぼう",
            }
        )
    if word.endswith("ぐ"):
        stem = word[:-1]
        forms.update(
            {
                stem + "いで",
                stem + "いだ",
                stem + "ぎます",
                stem + "ぎました",
                stem + "がない",
                stem + "げば",
                stem + "ごう",
            }
        )
    if word.endswith("つ"):
        stem = word[:-1]
        forms.update(
            {
                stem + "って",
                stem + "った",
                stem + "ちます",
                stem + "ちました",
                stem + "たない",
                stem + "てば",
                stem + "とう",
            }
        )
    if word.endswith("く") and not word.endswith("いく"):
        stem = word[:-1]
        forms.update(
            {
                stem + "いて",
                stem + "いた",
                stem + "きます",
                stem + "きました",
                stem + "かない",
                stem + "けば",
                stem + "こう",
            }
        )
    # устойчивые выражения: 人気が出る / 穴が開く / 雪が積もる / …
    if "が" in word:
        left, right = word.split("が", 1)
        for f in surface_forms(right):
            forms.add(left + "が" + f)
    if "を" in word and word.count("を") == 1:
        left, right = word.split("を", 1)
        for f in surface_forms(right):
            forms.add(left + "を" + f)
    # に優しい already full; 都合がいい / 都合が悪い
    if word.endswith("いい"):
        forms.add(word[:-2] + "よく")
    if word.endswith("悪い"):
        forms.update({word[:-2] + "悪く", word[:-2] + "悪くて"})
    return sorted(forms, key=len, reverse=True)


def find_surface(word: str, sentence: str) -> str:
    if word in sentence:
        return word
    for form in surface_forms(word):
        if form and form in sentence:
            return form
    raise ValueError(f"«{word}» (и формы) нет в: {sentence}")


def triple(word: str, j1: str, j2: str, j3: str) -> tuple[str, str]:
    w1, w2, w3 = find_surface(word, j1), find_surface(word, j2), find_surface(word, j3)
    e = f"{span(w1, j1)}<br>{span(w2, j2)}<br>{span(w3, j3)}"
    b = re.sub(r"<span class='study-word'>[^<]*</span>", "_____", e)
    return e, b


def triple_h(j1: str, w1: str, j2: str, w2: str, j3: str, w3: str) -> tuple[str, str]:
    e = f"{span(w1, j1)}<br>{span(w2, j2)}<br>{span(w3, j3)}"
    b = re.sub(r"<span class='study-word'>[^<]*</span>", "_____", e)
    return e, b


def pic(ru3: str, focus: str) -> str:
    return (
        "Иллюстрация учебная, 512×512: "
        + ru3
        + " Главный визуальный акцент — "
        + focus
        + ". Без любого текста, надписей и букв на изображении."
    )


def lesson_tag(lesson: str) -> str:
    n = lesson[1:] if lesson.startswith("L") else lesson
    return f"TOBIRA-II-第{int(n):02d}課"


def write_card(
    topic: str,
    word: str,
    reading: str,
    lesson: str,
    trans: str,
    hint: str,
    j1: str,
    j2: str,
    j3: str,
    r1: str,
    r2: str,
    r3: str,
    notes: str,
    kanji: str,
    furigana: str,
    extra_tags: list[str],
    img_focus: str,
    h1: str | None = None,
    h2: str | None = None,
    h3: str | None = None,
) -> None:
    if h1 or h2 or h3:
        ex, blank = triple_h(j1, h1 or word, j2, h2 or word, j3, h3 or word)
    else:
        ex, blank = triple(word, j1, j2, j3)
    tags = [topic] + extra_tags + ["N3", lesson_tag(lesson)]
    payload = {
        "Слово": word,
        "Перевод": trans,
        "Чтение": reading,
        "Подсказка": hint,
        "Пример": ex,
        "Пример без слова": blank,
        "Пример перевод": f"{r1}<br>{r2}<br>{r3}",
        "Картинка": pic(r3, img_focus),
        "Произношение": "",
        "Заметки": notes,
        "Кандзи-разбор": kanji,
        "Показать фуригану": furigana,
        "Теги": tags,
    }
    out = CARDS_DIR / topic / f"{word}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def append_wordlist(topic: str, words: list[str]) -> None:
    path = WORDS / topic
    if path.exists():
        lines = [ln.strip() for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip()]
    else:
        lines = []
    for w in words:
        if w not in lines:
            lines.append(w)
    lines.sort()
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


