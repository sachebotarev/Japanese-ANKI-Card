def expected_source_words(vocab: list[dict]) -> set[str]:
    out: set[str] = set()
    for item in vocab:
        lesson = item.get("lesson")
        lessons = item.get("lessons") or []
        word = item["word"]
        if word in SKIP:
            continue
        if lesson in LESSONS:
            out.add(word)
        elif word == "月" and "L20" in lessons:
            out.add(word)
    return out


def main() -> None:
    if not VOCAB_PATH.is_file():
        print(f"Ошибка: нет файла {VOCAB_PATH}", file=sys.stderr)
        sys.exit(1)
    vocab = json.loads(VOCAB_PATH.read_text(encoding="utf-8"))
    expected = expected_source_words(vocab)
    created: list[tuple[str, str]] = []

    def w(topic: str, word: str, lesson: str, **kw) -> None:
        write_card(topic, word, lesson=lesson, **kw)
        created.append((topic, word))

    define_cards(w)

    got_keys: set[str] = set()
    for _topic, word in created:
        matched = False
        for k, v in DISPLAY.items():
            if v == word:
                got_keys.add(k)
                matched = True
                break
        if not matched:
            got_keys.add(word)

    missing = expected - got_keys
    extra = got_keys - expected
    if missing:
        print(f"ПРЕДУПРЕЖДЕНИЕ: не созданы: {sorted(missing)}", file=sys.stderr)
        sys.exit(1)
    if extra:
        print(f"ПРЕДУПРЕЖДЕНИЕ: лишние: {sorted(extra)}", file=sys.stderr)
        sys.exit(1)

    by_topic: dict[str, list[str]] = {}
    for topic, word in created:
        by_topic.setdefault(topic, []).append(word)
    for topic, wl in by_topic.items():
        append_wordlist(topic, wl)

    print(f"Создано JSON: {len(created)}")
    for topic, word in created[:8]:
        print(f"  {CARDS_DIR / topic / (word + '.json')}")
    if len(created) > 8:
        print(f"  ... и ещё {len(created) - 8}")
    from collections import Counter
    c = Counter()
    for topic, word in created:
        data = json.loads((CARDS_DIR / topic / f"{word}.json").read_text(encoding="utf-8"))
        for tag in data["Теги"]:
            if tag.startswith("TOBIRA-II-"):
                c[tag] += 1
    print("По тегам:", dict(c))


if __name__ == "__main__":
    main()
