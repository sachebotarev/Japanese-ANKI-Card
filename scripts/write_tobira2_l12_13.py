def source_key_for(display_word: str) -> str:
    for k, v in DISPLAY.items():
        if v == display_word:
            return k
    return display_word


def main() -> None:
    if not VOCAB_PATH.is_file():
        print(f"Ошибка: нет файла {VOCAB_PATH}", file=sys.stderr)
        sys.exit(1)
    vocab = json.loads(VOCAB_PATH.read_text(encoding="utf-8"))
    expected = {
        item["word"]
        for item in vocab
        if min_lesson(item) in (12, 13)
    }
    created: list[tuple[str, str]] = []
    skipped: list[tuple[str, str]] = []

    def w(topic: str, word: str, lesson: str, **kw) -> None:
        ok = write_card(topic, word, lesson=lesson, **kw)
        if ok:
            created.append((topic, word))
        else:
            skipped.append((topic, word))

    define_cards(w)

    got_keys: set[str] = set()
    for topic, word in created + skipped:
        got_keys.add(source_key_for(word))

    missing = expected - got_keys
    if missing:
        print(f"ПРЕДУПРЕЖДЕНИЕ: не созданы: {sorted(missing)}", file=sys.stderr)
        sys.exit(1)

    by_topic: dict[str, list[str]] = {}
    for topic, word in created + skipped:
        by_topic.setdefault(topic, []).append(word)
    for topic, wl in by_topic.items():
        append_wordlist(topic, wl)

    print(f"Создано JSON: {len(created)}")
    print(f"Пропущено (уже есть): {len(skipped)}")
    print(f"Ожидалось по источнику: {len(expected)}")
    samples = (created or skipped)[:8]
    for topic, word in samples:
        print(f"  {CARDS_DIR / topic / (word + '.json')}")
    if len(created) + len(skipped) > 8:
        print(f"  ... и ещё {len(created) + len(skipped) - 8}")


if __name__ == "__main__":
    main()
