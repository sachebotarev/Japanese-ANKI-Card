def grouped_examples(kind: str, word: str, nom: str, oblique: str):
    if kind == "field":
        return (
            ["ここに{w}があります。", "この{w}は広いです。", "雨がやんだので、{w}を見に行って、写真を撮りました。"],
            [f"Здесь есть {nom}.", f"Это {nom} большое.", f"Когда дождь закончился, я отправился посмотреть на {oblique} и сделал фотографию."],
        )
    if kind == "forest":
        return (
            ["あそこに{w}があります。", "この{w}には鳥がいます。", "天気がよかったので、{w}を歩いて、鳥の声を聞きました。"],
            [f"Вон там есть {nom}.", f"В {oblique} живут птицы.", f"Погода была хорошей, поэтому я гулял в {oblique} и слушал пение птиц."],
        )
    if kind == "mountain":
        return (
            ["あそこに{w}が見えます。", "この{w}は高いです。", "晴れたので、{w}を見に行って、写真を撮りました。"],
            [f"Вон там виднеется {nom}.", "Эта гора высокая." if word == "高山" else f"Этот {nom} высокий.", f"Прояснилось, поэтому я пошёл посмотреть на {oblique} и сфотографировал его."],
        )
    if kind == "bird":
        return (
            ["{w}がいます。", "この公園には{w}がいます。", "朝早く公園に行ったら、{w}が木に止まっていたので、写真を撮りました。"],
            [f"Здесь есть {nom}.", f"В этом парке живёт {nom}.", f"Когда я рано утром пришёл в парк, я увидел {oblique} на дереве и сфотографировал её."],
        )
    raise ValueError(kind)


def build(word, reading, translation, topic, level, jp, ru, hint):
    marked = [s.format(w=f"<span class='study-word'>{word}</span>") for s in jp]
    assert len(marked) == len(ru) == 3
    blank = [s.replace("{w}", "_____") for s in jp]
    chars = list(dict.fromkeys(re.findall(r"[一-龯]", word)))
    assert all(c in KANJI for c in chars), word
    return {
        "Слово": word, "Перевод": translation, "Чтение": reading,
        "Подсказка": hint,
        "Пример": "<br>".join(marked),
        "Пример без слова": "<br>".join(blank),
        "Пример перевод": "<br>".join(ru),
        "Картинка": (
            "Anime illustration, square 1:1, 512x512. One person, natural outdoor scene. "
            f"Visual focus: {translation}. Scene: {ru[2]} "
            "No text, no letters, no signs, no watermark."
        ),
        "Произношение": "",
        "Заметки": "Слово из словарных заметок Basic Kanji Books, тома 1–2.",
        "Кандзи-разбор": "; ".join(f"{c} — {KANJI[c]}" for c in chars),
        "Показать фуригану": "N",
        "Теги": [topic, "名詞", level],
    }


def main():
    source = {x["word"]: x for x in json.loads(SOURCE.read_text(encoding="utf-8"))}
    cards = []
    for kind, items in GROUPS.items():
        for word, translation, nom, oblique, topic, level in items:
            jp, ru = grouped_examples(kind, word, nom, oblique)
            cards.append(build(word, source[word]["reading"], translation, topic, level, jp, ru, GROUP_HINTS[kind]))
    for word, translation, topic, level, jp, ru in CUSTOM:
        cards.append(build(word, source[word]["reading"], translation, topic, level, jp, ru, HINTS[word]))
    assert len(cards) == len({c["Слово"] for c in cards})
    for card in cards:
        topic, word = card["Теги"][0], card["Слово"]
        out = ROOT / "Карточки" / topic / f"{word}.json"
        if out.exists():
            raise FileExistsError(out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(card, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        words = ROOT / "Слова" / topic
        lines = set(words.read_text(encoding="utf-8").splitlines()) if words.exists() else set()
        lines.add(word)
        words.write_text("\n".join(sorted(x.strip() for x in lines if x.strip())) + "\n", encoding="utf-8")
    print(f"Создано {len(cards)} карточек")


if __name__ == "__main__":
    main()
