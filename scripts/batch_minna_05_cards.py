MINNA = ["みんなの日本語", "みんな初級I-第05課"]


def span(word: str, sentence: str) -> str:
    if word not in sentence:
        raise ValueError(f"«{word}» нет в: {sentence}")
    return sentence.replace(word, f"<span class='study-word'>{word}</span>", 1)


def triple(word: str, j1: str, j2: str, j3: str) -> tuple[str, str]:
    e = f"{span(word, j1)}<br>{span(word, j2)}<br>{span(word, j3)}"
    b = re.sub(r"<span class='study-word'>[^<]*</span>", "_____", e)
    return e, b


def write_card(
    topic: str,
    word: str,
    reading: str,
    trans: str,
    hint: str,
    j1: str,
    j2: str,
    j3: str,
    r1: str,
    r2: str,
    r3: str,
    notes: str,
    kanji: str,
    furigana: str,
    extra_tags: list[str],
    img_prompt: str,
) -> None:
    ex, blank = triple(word, j1, j2, j3)
    tags = [topic] + extra_tags + MINNA
    payload = {
        "Слово": word,
        "Перевод": trans,
        "Чтение": reading,
        "Подсказка": hint,
        "Пример": ex,
        "Пример без слова": blank,
        "Пример перевод": f"{r1}<br>{r2}<br>{r3}",
        "Картинка": img_prompt,
        "Произношение": "",
        "Заметки": notes,
        "Кандзи-разбор": kanji,
        "Показать фуригану": furigana,
        "Теги": tags,
    }
    out = CARDS / topic / f"{word}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def normalize_word_files() -> None:
    """Добавляет слова в Слова/<тема> и сортирует по Unicode."""
    added: dict[str, set[str]] = {}
    for p in CARDS.rglob("*.json"):
        rel = p.relative_to(CARDS)
        if len(rel.parts) < 2:
            continue
        topic = rel.parts[0]
        try:
            d = json.loads(p.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            continue
        w = d.get("Слово")
        if not w:
            continue
        added.setdefault(topic, set()).add(str(w))
    for topic, ws in added.items():
        path = WORDS / topic
        if not path.is_file():
            path.parent.mkdir(parents=True, exist_ok=True)
        lines = []
        if path.exists():
            lines = [ln.strip() for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip()]
        for w in ws:
            if w not in lines:
                lines.append(w)
        lines = sorted(set(lines))
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")


