def span(word: str, sentence: str) -> str:
    if word not in sentence:
        raise ValueError(f"«{word}» нет в: {sentence}")
    return sentence.replace(word, f"<span class='study-word'>{word}</span>", 1)


def triple(
    word: str, j1: str, j2: str, j3: str, forms: list[str] | None = None
) -> tuple[str, str]:
    surfaces = forms or [word, word, word]
    e = (
        f"{span(surfaces[0], j1)}<br>{span(surfaces[1], j2)}"
        f"<br>{span(surfaces[2], j3)}"
    )
    b = re.sub(r"<span class='study-word'>[^<]*</span>", "_____", e)
    return e, b


def pic(ru3: str, focus: str) -> str:
    return (
        "Иллюстрация учебная, 512×512: "
        + ru3
        + " Главный визуальный акцент — "
        + focus
        + ". Без любого текста, надписей и букв на изображении."
    )


def write_card(
    topic: str,
    word: str,
    reading: str,
    trans: str,
    hint: str,
    j1: str,
    j2: str,
    j3: str,
    r1: str,
    r2: str,
    r3: str,
    notes: str,
    kanji: str,
    furigana: str,
    extra_tags: list[str],
    img_prompt: str,
    jlpt: str = "N5",
    minna_lesson: str | None = None,
    skip_existing: bool = True,
    example_forms: list[str] | None = None,
) -> bool:
    out = CARDS / topic / f"{word}.json"
    if skip_existing and out.exists():
        return False
    ex, blank = triple(word, j1, j2, j3, example_forms)
    tags = [topic] + extra_tags + MINNA
    if jlpt not in tags:
        tags.append(jlpt)
    if minna_lesson:
        tags.insert(1, minna_lesson)
    payload = {
        "Слово": word,
        "Перевод": trans,
        "Чтение": reading,
        "Подсказка": hint,
        "Пример": ex,
        "Пример без слова": blank,
        "Пример перевод": f"{r1}<br>{r2}<br>{r3}",
        "Картинка": img_prompt,
        "Произношение": "",
        "Заметки": notes,
        "Кандзи-разбор": kanji,
        "Показать фуригану": furigana,
        "Теги": tags,
    }
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return True


def append_wordlist(topic: str, words: list[str]) -> None:
    path = WORDS / topic
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = []
    if path.exists():
        lines = [ln.strip() for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip()]
    for w in words:
        if w not in lines:
            lines.append(w)
    lines.sort()
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


