def span(word: str, sentence: str) -> str:
    if word not in sentence:
        raise ValueError(f"«{word}» нет в: {sentence}")
    return sentence.replace(word, f"<span class='study-word'>{word}</span>", 1)


def triple(word: str, j1: str, j2: str, j3: str) -> tuple[str, str]:
    e = f"{span(word, j1)}<br>{span(word, j2)}<br>{span(word, j3)}"
    b = re.sub(r"<span class='study-word'>[^<]*</span>", "_____", e)
    return e, b


def pic(ru3: str, focus: str) -> str:
    return (
        "Иллюстрация учебная, 512×512: "
        + ru3
        + " Главный визуальный акцент — "
        + focus
        + ". Без любого текста, надписей и букв на изображении."
    )


def write_card(
    topic: str,
    word: str,
    reading: str,
    trans: str,
    hint: str,
    j1: str,
    j2: str,
    j3: str,
    r1: str,
    r2: str,
    r3: str,
    notes: str,
    kanji: str,
    furigana: str,
    extra_tags: list[str],
    img_prompt: str,
) -> None:
    ex, blank = triple(word, j1, j2, j3)
    tags = [topic] + extra_tags + MINNA
    payload = {
        "Слово": word,
        "Перевод": trans,
        "Чтение": reading,
        "Подсказка": hint,
        "Пример": ex,
        "Пример без слова": blank,
        "Пример перевод": f"{r1}<br>{r2}<br>{r3}",
        "Картинка": img_prompt,
        "Произношение": "",
        "Заметки": notes,
        "Кандзи-разбор": kanji,
        "Показать фуригану": furigana,
        "Теги": tags,
    }
    out = CARDS / topic / f"{word}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def append_wordlist(topic: str, words: list[str]) -> None:
    path = WORDS / topic
    lines = [ln.strip() for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip()]
    for w in words:
        if w not in lines:
            lines.append(w)
    lines.sort()
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def add_lesson_tag_to_existing(words: list[str]) -> int:
    n = 0
    tag = "みんな初級I-第16課"
    for p in CARDS.rglob("*.json"):
        data = json.loads(p.read_text(encoding="utf-8"))
        if data.get("Слово") not in words:
            continue
        tags = list(data.get("Теги") or [])
        if tag in tags:
            continue
        tags.append(tag)
        if "みんなの日本語" not in tags:
            tags.append("みんなの日本語")
        data["Теги"] = tags
        p.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        n += 1
    return n


