#!/usr/bin/env python3
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CARDS = ROOT / "Карточки"
WORDS = ROOT / "Слова"


def span(sentence: str, target: str) -> str:
    if target not in sentence:
        raise ValueError(f"Нет «{target}» в примере: {sentence}")
    return sentence.replace(target, f"<span class='study-word'>{target}</span>", 1)


def examples(targets: tuple[str, str, str], jp: tuple[str, str, str]) -> tuple[str, str]:
    marked = [span(s, t) for s, t in zip(jp, targets)]
    full = "<br>".join(marked)
    blank = re.sub(r"<span class='study-word'>[^<]*</span>", "_____", full)
    return full, blank


def picture(ru3: str, focus: str) -> str:
    return (
        "masterpiece, best quality, anime illustration, square 1:1, 512x512, "
        f"scene: {ru3}, main visual focus: {focus}, "
        "clear physical subject, natural poses, detailed hands, cinematic storytelling composition, "
        "no text, no letters, no signs, no watermark. Negative prompt: third person, extra person, "
        "crowd, background people, text, letters, typography, words, subtitles, watermark, logo, "
        "signature, kanji on objects, worst quality, low quality, blurry, bad anatomy, bad hands, "
        "extra fingers, deformed face."
    )


def write_wordlist(topic: str, word: str) -> None:
    path = WORDS / topic
    path.parent.mkdir(parents=True, exist_ok=True)
    lines: list[str] = []
    if path.exists():
        lines = [x.strip() for x in path.read_text(encoding="utf-8").splitlines() if x.strip()]
    if word not in lines:
        lines.append(word)
    path.write_text("\n".join(sorted(set(lines))) + "\n", encoding="utf-8")


def write_card(c: dict) -> tuple[Path, bool]:
    topic = c["topic"]
    word = c["word"]
    out = CARDS / topic / f"{word}.json"
    write_wordlist(topic, word)
    if out.exists():
        return out, False

    ex, blank = examples(c["targets"], c["jp"])
    payload = {
        "Слово": word,
        "Перевод": c["translation"],
        "Чтение": c["reading"],
        "Подсказка": c["hint"],
        "Пример": ex,
        "Пример без слова": blank,
        "Пример перевод": "<br>".join(c["ru"]),
        "Картинка": picture(c["ru"][2], c["focus"]),
        "Произношение": "",
        "Заметки": c["notes"],
        "Кандзи-разбор": c["kanji"],
        "Показать фуригану": c["furigana"],
        "Теги": c["tags"],
    }
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return out, True


