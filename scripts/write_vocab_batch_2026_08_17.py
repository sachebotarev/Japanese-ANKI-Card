EXISTING_WORD_TOPICS = {
    "理由": "Общение",
    "ちょうど": "Наречия",
    "特に": "Наречия",
    "ワクワク": "Наречия",
    "やはり": "Наречия",
    "道具": "Быт",
    "情報": "Общение",
    "届く": "Глаголы",
}


def main() -> int:
    created: list[Path] = []
    skipped: list[Path] = []
    for word, topic in EXISTING_WORD_TOPICS.items():
        write_wordlist(topic, word)
    for c in CARDS_DATA:
        path, was_created = write_card(c)
        (created if was_created else skipped).append(path)

    print(f"created={len(created)} skipped_existing={len(skipped)}")
    for path in created:
        print(f"created {path.relative_to(ROOT)}")
    for path in skipped:
        print(f"existing {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
