def main() -> None:
    if not VOCAB_PATH.is_file():
        print(f"Ошибка: нет файла {VOCAB_PATH}", file=sys.stderr)
        sys.exit(1)
    vocab = [
        item
        for item in json.loads(VOCAB_PATH.read_text(encoding="utf-8"))
        if item.get("lesson") in LESSONS
    ]
    expected = {item["word"] for item in vocab}
    created: list[tuple[str, str]] = []

    def w(topic: str, word: str, lesson: str, **kw) -> None:
        write_card(topic, word, lesson=lesson, **kw)
        created.append((topic, word))

    define_cards(w)

    got_keys: set[str] = set()
    for _topic, word in created:
        matched = False
        for k, v in DISPLAY.items():
            if v == word:
                got_keys.add(k)
                matched = True
                break
        if not matched:
            got_keys.add(word)

    missing = expected - got_keys
    extra = got_keys - expected
    if missing:
        print(f"ПРЕДУПРЕЖДЕНИЕ: не созданы: {sorted(missing)}", file=sys.stderr)
        sys.exit(1)
    if extra:
        print(f"ПРЕДУПРЕЖДЕНИЕ: лишние ключи: {sorted(extra)}", file=sys.stderr)
        sys.exit(1)

    by_topic: dict[str, list[str]] = {}
    for topic, word in created:
        by_topic.setdefault(topic, []).append(word)
    for topic, wl in by_topic.items():
        append_wordlist(topic, wl)

    print(f"Создано JSON: {len(created)}")
    print(f"  L16: {sum(1 for t, w in created if (CARDS_DIR / t / f'{w}.json').exists())}")
    # count by lesson tag
    l16 = l17 = 0
    for topic, word in created:
        data = json.loads((CARDS_DIR / topic / f"{word}.json").read_text(encoding="utf-8"))
        tags = data.get("Теги") or []
        if any("第16課" in t for t in tags):
            l16 += 1
        if any("第17課" in t for t in tags):
            l17 += 1
    print(f"  по тегам: L16={l16}, L17={l17}")
    samples = [
        "Наречия/によって.json",
        "Наречия/今まで.json",
        "Наречия/特に.json",
        "Наречия/急に.json",
        "Финансы/お金を貯める.json",
    ]
    print("Примеры путей:")
    for s in samples:
        print(f"  {CARDS_DIR / s}")
    for topic, word in created[:3]:
        print(f"  {CARDS_DIR / topic / (word + '.json')}")


if __name__ == "__main__":
    main()
